// =========================================================
// ARCHIE CONVERSATIONAL ENGLISH EXPANSION CORPUS
//
// Versioned conversational training data for the native
// NLU intent classifier. The corpus is DATA, never code:
// every example teaches the underlying PATTERN of a
// conversational exchange so the trained Naive Bayes
// classifier can GENERALIZE to unseen variations. No
// response is hardcoded against any example.
//
// CONSTRAINTS (enforced by conversational-expansion.test.ts):
//   * no hyphens in any example sentence (owner directive)
//   * no duplicate utterance inside this corpus or against
//     the base NLU corpus (duplicates bias the classifier)
//   * no held-out phrase appears verbatim in training data
//     (memorization is not generalization)
//   * every intent in this corpus is handled honestly by
//     the engine's conversational route (no fake responses)
//
// Integration (owner directive, 2026-09-11):
//   * nlu.ts concatenates CONVERSATION_CORPUS into CORPUS
//     at train time, so all surfaces (ARCHIE Core, chat,
//     Studio, WhatsApp) learn the same patterns
//   * conversational outcomes flow through the existing
//     learning pipeline: politeness and social exchange are
//     ACKNOWLEDGEMENT, never verification evidence. User
//     feedback never becomes truth automatically
//   * emoji understanding lives in emoji.ts; this corpus
//     includes emoji enhanced examples so the classifier
//     is robust to emoji decorated messages, while pure
//     emoji messages route deterministically by tone
// =========================================================

