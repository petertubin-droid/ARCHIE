/** Fast membership set for the corrector: a seeded word is a
 *  known word, never a typo-correction target. */
const SEED_TERM_SET: ReadonlySet<string> = new Set(
  SEED_VOCABULARY.map((e) => e.term),
);

export function isSeedTerm(term: string): boolean {
  return SEED_TERM_SET.has(term);
}

/** Terms learned live from conversation (per-isolate module
 *  registry, warmed by archie-chat each owner request from
 *  frelux_vocabulary). A learned term is a known word from
 *  the moment it is first seen. */
let learnedTermSet: ReadonlySet<string> = new Set<string>();

export function registerLearnedTerms(terms: string[]): void {
  learnedTermSet = new Set(terms.map((t) => t.toLowerCase()));
}

/** Known to the engine by seed or by live learning. Used by
 *  the typo corrector (known words are never corrected) and
 *  by the unknown-word capture (never re-capture known). */
export function isKnownVocabularyTerm(term: string): boolean {
  // Wh-contractions are grammar, not vocabulary: the typo
  // corrector must normalize them even if one slipped into
  // the registry. See isWhContraction for the incident.
  if (isWhContraction(term)) return false;
  const t = term.toLowerCase();
  return SEED_TERM_SET.has(t) || learnedTermSet.has(t);
}

/** Seed entries as fact rows for the engine knowledge store
 *  (subject = term, predicate = means, object = meaning) —
 *  definitions become answerable through the normal honest
 *  knowledge path with provenance. */
export function seedMeansFacts(): Array<{
  subject: string;
  predicate: string;
  object: string;
  confidence: number;
  provenance: { source: string };
}> {
  return SEED_VOCABULARY.map((e) => ({
    subject: e.term,
    predicate: "means",
    object: e.meaning,
    confidence: 0.9,
    provenance: { source: "seed vocabulary" },
  }));
}

