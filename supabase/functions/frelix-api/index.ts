interface KeyRow {
  id: string;
  user_id: string;
  name: string;
  status: string;
  permissions: string[];
  plan_key: string;
  rate_limit_per_minute: number;
  daily_quota: number;
  monthly_quota: number;
  expires_at: string | null;
}

interface AuthedRequest {
  key: KeyRow;
  requestId: string;
}

/**
 * §23 Observability / abuse detection: meter an authentication
 * failure for an UNKNOWN key (wrong format or no matching hash).
 * The row has no key/user attribution BY DESIGN — no raw key,
 * hash fragment, or prefix is ever stored (§3).
 */
async function meterAuthFailure(
  req: Request,
  requestId: string,
  capability: string,
  errorCode: string,
): Promise<void> {
  const url = new URL(req.url);
  await svc.from("frelux_api_usage").insert({
    api_key_id: null,
    user_id: null,
    request_id: requestId,
    endpoint: url.pathname.replace(/^.*frelix-api\//, "/"),
    capability,
    method: req.method,
    status_code: 401,
    latency_ms: 0,
    provider: null,
    usage_units: 0,
    billing_unit: "request",
    cost: 0,
    region: null,
    error_code: errorCode,
  });
}

async function usageCount(keyId: string, sinceIso: string): Promise<number> {
  const { count, error } = await svc
    .from("frelux_api_usage")
    .select("id", { count: "exact", head: true })
    .gte("created_at", sinceIso)
    .eq("api_key_id", keyId)
    // Only billable requests count — denials are metered with
    // usage_units = 0 and never tighten the self-recovery window.
    .gt("usage_units", 0);
  if (error) return 0;
  return count ?? 0;
}

async function authenticate(
  req: Request,
  requestId: string,
  capability: string,
): Promise<{ auth?: AuthedRequest; denial?: Response }> {
  const token = extractBearerToken(req.headers.get("Authorization"));
  if (!token || !isValidApiKeyFormat(token)) {
    await meterAuthFailure(req, requestId, capability, "invalid_api_key");
    return {
      denial: json(
        401,
        {
          ...apiError(
            "invalid_api_key",
            "Provide a valid FRELUX API key: Authorization: Bearer FLX-…",
            requestId,
          ),
        },
        requestId,
      ),
    };
  }

  const keyHash = await hashApiKey(token); // raw key never stored/logged
  const { data: row, error } = await svc
    .from("frelux_api_keys")
    .select(
      "id,created_by,name,status,permissions,plan_key,rate_limit_per_minute,daily_quota,monthly_quota,expires_at",
    )
    .eq("key_hash", keyHash)
    .maybeSingle();
  if (error || !row) {
    await meterAuthFailure(req, requestId, capability, "invalid_api_key");
    return {
      denial: json(
        401,
        apiError("invalid_api_key", "API key is invalid.", requestId),
        requestId,
      ),
    };
  }

  // The tenant is the key OWNER (created_by) — resolved from the
  // stored record, never from any client-provided field.
  const key: KeyRow = {
    ...row,
    user_id: row.created_by,
    permissions: Array.isArray(row.permissions) ? row.permissions : [],
  };

  // Status / revocation / expiration (§5)
  const statusVerdict = evaluateKeyStatus(
    { ...key, status: key.status as "active" },
    new Date(),
  );
  if (!statusVerdict.ok) {
    await meter(key, requestId, req, 401, capability, 0, statusVerdict.code, {
      usageUnits: 0,
    });
    return {
      denial: json(
        401,
        apiError(
          statusVerdict.code,
          statusVerdict.code === "expired_api_key"
            ? "This API key has expired. Rotate it from the Developer Portal."
            : "This API key is no longer active.",
          requestId,
        ),
        requestId,
      ),
    };
  }

  // Per-minute rate limit (durable metering count — §21)
  const minuteAgo = new Date(Date.now() - 60_000).toISOString();
  const recent = await usageCount(key.id, minuteAgo);
  const rl = evaluateRateLimit(recent, key.rate_limit_per_minute);
  if (!rl.allowed) {
    await meter(
      key,
      requestId,
      req,
      429,
      capability,
      0,
      "rate_limit_exceeded",
      {
        usageUnits: 0,
      },
    );
    return {
      denial: json(
        429,
        {
          ...apiError(
            "rate_limit_exceeded",
            `Rate limit of ${key.rate_limit_per_minute} requests/minute exceeded.`,
            requestId,
          ),
          retryAfterSeconds: rl.retryAfterSeconds,
        },
        requestId,
      ),
    };
  }

  // Daily / monthly quotas (§5, §16)
  const dayStart = new Date();
  dayStart.setUTCHours(0, 0, 0, 0);
  const monthStart = new Date(
    Date.UTC(dayStart.getUTCFullYear(), dayStart.getUTCMonth(), 1),
  );
  const daily = await usageCount(key.id, dayStart.toISOString());
  const dq = evaluateQuota("daily", daily, key.daily_quota);
  if (!dq.allowed) {
    await meter(
      key,
      requestId,
      req,
      429,
      capability,
      0,
      "daily_quota_exceeded",
      {
        usageUnits: 0,
      },
    );
    return {
      denial: json(
        429,
        {
          ...apiError(
            "daily_quota_exceeded",
            `Daily quota of ${key.daily_quota} requests exceeded.`,
            requestId,
          ),
          retryAfterSeconds: dq.retryAfterSeconds,
        },
        requestId,
      ),
    };
  }
  const monthly = await usageCount(key.id, monthStart.toISOString());
  const mq = evaluateQuota("monthly", monthly, key.monthly_quota);
  if (!mq.allowed) {
    await meter(
      key,
      requestId,
      req,
      429,
      capability,
      0,
      "monthly_quota_exceeded",
      {
        usageUnits: 0,
      },
    );
    return {
      denial: json(
        429,
        {
          ...apiError(
            "monthly_quota_exceeded",
            `Monthly quota of ${key.monthly_quota} requests exceeded.`,
            requestId,
          ),
          retryAfterSeconds: mq.retryAfterSeconds,
        },
        requestId,
      ),
    };
  }

  // Requested capability (§5)
  if (!capabilityAllowed(key.permissions, capability)) {
    await meter(
      key,
      requestId,
      req,
      403,
      capability,
      0,
      "capability_not_allowed",
    );
    return {
      denial: json(
        403,
        apiError(
          "capability_not_allowed",
          `This API key does not have the "${capability}" capability.`,
          requestId,
        ),
        requestId,
      ),
    };
  }

  return { auth: { key, requestId }, denial: undefined };
}

/** Plan region entitlement for a region-scoped request (§11). */
async function checkPlanRegion(
  key: KeyRow,
  requestedRegion: string | null,
): Promise<boolean> {
  const { data: plan } = await svc
    .from("frelux_api_plans")
    .select("config")
    .eq("key", key.plan_key)
    .maybeSingle();
  if (!plan?.config) return requestedRegion === null;
  return regionAllowed(
    (plan.config as { regions?: unknown }).regions,
    requestedRegion,
  );
}

// ---------------------------------------------------------
// Metering (§15) — metadata only, no request content.
// ---------------------------------------------------------
async function meter(
  key: KeyRow,
  requestId: string,
  req: Request,
  statusCode: number,
  capability: string,
  latencyMs: number,
  errorCode?: string,
  opts?: { provider?: string; usageUnits?: number; region?: string },
) {
  const url = new URL(req.url);
  await svc.from("frelux_api_usage").insert({
    api_key_id: key.id,
    user_id: key.user_id,
    request_id: requestId,
    endpoint: url.pathname.replace(/^.*frelix-api\//, "/"),
    capability,
    method: req.method,
    status_code: statusCode,
    latency_ms: Math.round(latencyMs),
    provider: opts?.provider ?? null,
    usage_units: opts?.usageUnits ?? 1,
    billing_unit: "request",
    cost: 0,
    region: opts?.region ?? null,
    error_code: errorCode ?? null,
  });
  if (statusCode < 400) {
    await svc
      .from("frelux_api_keys")
      .update({ last_used_at: new Date().toISOString() })
      .eq("id", key.id);
  }
}

// ---------------------------------------------------------
// Body handling with request-size limits.
// ---------------------------------------------------------
async function readJson(
  req: Request,
): Promise<{ body?: Record<string, unknown>; error?: Response }> {
  const declared = req.headers.get("content-length");
  if (declared && Number(declared) > MAX_BODY_BYTES) {
    return {
      error: json(
        413,
        apiError("payload_too_large", "Request body exceeds 100KB."),
      ),
    };
  }
  try {
    const text = await req.text();
    if (text.length === 0) return { body: {} };
    if (text.length > MAX_BODY_BYTES) {
      return {
        error: json(
          413,
          apiError("payload_too_large", "Request body exceeds 100KB."),
        ),
      };
    }
    const parsed = JSON.parse(text);
    if (
      typeof parsed !== "object" ||
      parsed === null ||
      Array.isArray(parsed)
    ) {
      return {
        error: json(
          400,
          apiError("invalid_request", "Request body must be a JSON object."),
        ),
      };
    }
    return { body: parsed as Record<string, unknown> };
  } catch {
    return {
      error: json(
        400,
        apiError("invalid_json", "Request body is not valid JSON."),
      ),
    };
  }
}

// ---------------------------------------------------------
// AI provider abstraction (§7) — FRELUX is the identity; the
// provider is internal infrastructure and never appears in
// API responses.
// ---------------------------------------------------------
interface ProviderCall {
  provider: string;
  model: string;
  call: () => Promise<string | null>;
}

function resolveProvider(
  systemPrompt: string,
  userPrompt: string,
): ProviderCall | null {
  if (OPENAI_API_KEY) {
    return {
      provider: "openai",
      model: OPENAI_API_MODEL,
      call: async () => {
        const res = await fetch("https://api.openai.com/v1/chat/completions", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${OPENAI_API_KEY}`,
          },
          body: JSON.stringify({
            model: OPENAI_API_MODEL,
            temperature: 0,
            response_format: { type: "json_object" },
            messages: [
              { role: "system", content: systemPrompt },
              { role: "user", content: userPrompt },
            ],
          }),
          signal: AbortSignal.timeout(PROVIDER_TIMEOUT_MS),
        });
        if (!res.ok) return null;
        const data = await res.json();
        return data?.choices?.[0]?.message?.content ?? null;
      },
    };
  }
  if (GEMINI_API_KEY) {
    return {
      provider: "gemini",
      model: GEMINI_MODEL,
      call: async () => {
        const res = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent?key=${GEMINI_API_KEY}`,
          {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              contents: [
                { parts: [{ text: `${systemPrompt}\n\n${userPrompt}` }] },
              ],
              generationConfig: {
                temperature: 0,
                responseMimeType: "application/json",
              },
            }),
            signal: AbortSignal.timeout(PROVIDER_TIMEOUT_MS),
          },
        );
        if (!res.ok) return null;
        const data = await res.json();
        return data?.candidates?.[0]?.content?.parts?.[0]?.text ?? null;
      },
    };
  }
  return null;
}

