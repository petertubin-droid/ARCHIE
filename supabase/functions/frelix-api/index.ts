async function handleFeedback(req: Request, auth: AuthedRequest) {
  const started = Date.now();
  const { body, error } = await readJson(req);
  if (error) return error;

  const topic = typeof body.topic === "string" ? body.topic.trim() : "";
  const recommendation =
    typeof body.recommendation === "string" ? body.recommendation.trim() : "";
  const capability =
    typeof body.capability === "string" ? body.capability.trim() : "";
  const region =
    typeof body.region === "string" && body.region.trim()
      ? body.region.trim().toUpperCase()
      : null;

  if (topic.length < 3 || topic.length > 200) {
    return json(
      400,
      apiError(
        "invalid_request",
        '"topic" must be 3–200 characters.',
        auth.requestId,
      ),
      auth.requestId,
    );
  }
  if (recommendation.length < 3 || recommendation.length > 2000) {
    return json(
      400,
      apiError(
        "invalid_request",
        '"recommendation" must be 3–2000 characters.',
        auth.requestId,
      ),
      auth.requestId,
    );
  }
  if (capability.length < 2 || capability.length > 100) {
    return json(
      400,
      apiError(
        "invalid_request",
        '"capability" must be 2–100 characters.',
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  // High-risk knowledge gets flagged for engineering review —
  // never auto-promoted, consistent with Phase 6.5 governance.
  const highRisk =
    /structural|foundation|load[- ]?bearing|engineer|safety|column|beam|slab/i.test(
      `${topic} ${recommendation}`,
    );

  // USER_PROVIDED — enters as CANDIDATE. No API path promotes it.
  const { error: insertError } = await svc
    .from("frelux_learning_records")
    .insert({
      source: "USER",
      source_type: "frelux_api",
      topic,
      capability,
      recommendation,
      proposed_scope: region ? "REGIONAL" : "GLOBAL",
      scope_key: region ?? null,
      evidence: [
        {
          channel: "frelux_api",
          request_id: auth.requestId,
          api_key_name: auth.key.name,
        },
      ],
      lifecycle_status: "CANDIDATE",
      requires_engineering_review: highRisk,
    });

  await meter(
    auth.key,
    auth.requestId,
    req,
    insertError ? 503 : 201,
    "feedback",
    Date.now() - started,
    insertError ? "insert_failed" : undefined,
    { region: region ?? undefined },
  );

  if (insertError) {
    return json(
      503,
      apiError(
        "feedback_unavailable",
        "Feedback could not be recorded. Retry with backoff.",
        auth.requestId,
      ),
      auth.requestId,
    );
  }
  return json(
    201,
    {
      api: "FRELUX AI API",
      version: API_VERSION,
      status: "submitted",
      lifecycle: "CANDIDATE",
      requiresEngineeringReview: highRisk,
      note: "USER_PROVIDED ≠ SYSTEM_VERIFIED ≠ APPROVED. API feedback enters the FRELUX learning governance pipeline and is reviewed by humans before any knowledge is approved or versioned.",
      requestId: auth.requestId,
    },
    auth.requestId,
  );
}

