async function handleCalculator(
  req: Request,
  auth: AuthedRequest,
  engineId: string,
) {
  const started = Date.now();
  const { body, error } = await readJson(req);
  if (error) return error;

  const descriptor = listEngines().find((e) => e.id === engineId);
  if (!descriptor) {
    await meter(
      auth.key,
      auth.requestId,
      req,
      404,
      "calculators",
      Date.now() - started,
      "unknown_engine",
    );
    return json(
      404,
      apiError(
        "unknown_engine",
        `Unknown calculator "${engineId}". Available engines: ${ENGINE_IDS()}.`,
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  // §9/§10: the canonical engine is the ONLY execution path. The
  // gateway never invents missing values — validation failures
  // come back as structured responses from the engine itself.
  const result = await executeEngine(engineId, body.input ?? body);
  const latency = Date.now() - started;

  await meter(
    auth.key,
    auth.requestId,
    req,
    result.ok ? 200 : 422,
    "calculators",
    latency,
    result.ok ? undefined : "validation_failed",
    {
      region:
        typeof (body as { region?: unknown }).region === "string"
          ? (body as { region: string }).region
          : undefined,
    },
  );

  if (!result.ok) {
    return json(
      422,
      {
        ...apiError(
          "validation_failed",
          "The calculation input is incomplete or invalid. FRELUX does not invent missing values.",
          auth.requestId,
        ),
        engine: engineId,
        details: result.error,
      },
      auth.requestId,
    );
  }

  return json(
    200,
    {
      api: "FRELUX AI API",
      version: API_VERSION,
      engine: engineId,
      deterministic: true,
      calculatedBy: descriptor.creditedAs,
      result,
      requestId: auth.requestId,
    },
    auth.requestId,
  );
}

async function handleChat(req: Request, auth: AuthedRequest) {
  const started = Date.now();
  const { body, error } = await readJson(req);
  if (error) return error;

  const message = body.message;
  if (
    typeof message !== "string" ||
    message.length === 0 ||
    message.length > 4000
  ) {
    return json(
      400,
      apiError(
        "invalid_request",
        '"message" must be a non-empty string (max 4000 chars).',
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  // Region context (§11) — explicit only; never a silent fallback.
  let regionNote =
    "The user did not state a region. If the answer depends on regional prices, materials, standards or practices, ask for the region instead of assuming any default.";
  const region = body.region;
  if (
    typeof region === "object" &&
    region !== null &&
    typeof (region as Record<string, unknown>).country === "string"
  ) {
    const r = region as { country: string; state?: string; city?: string };
    const requested = r.country.toUpperCase();
    if (!(await checkPlanRegion(auth.key, requested))) {
      await meter(
        auth.key,
        auth.requestId,
        req,
        403,
        "chat",
        Date.now() - started,
        "region_not_available_for_plan",
      );
      return json(
        403,
        apiError(
          "region_not_available_for_plan",
          `Region "${requested}" is not included in this API key's plan.`,
          auth.requestId,
        ),
        auth.requestId,
      );
    }
    regionNote = `Region context: country=${r.country}${r.state ? `, state=${r.state}` : ""}${r.city ? `, city=${r.city}` : ""}. Ground prices, materials, standards and terminology in this region when known; be explicit about freshness and confidence.`;
    await meter(
      auth.key,
      auth.requestId,
      req,
      200,
      "chat",
      Date.now() - started,
      undefined,
      {
        region: requested,
      },
    );
  }

  const provider = resolveProvider(
    CHAT_SYSTEM_PROMPT(),
    buildChatUserPrompt(message, regionNote),
  );
  if (!provider) {
    await meter(
      auth.key,
      auth.requestId,
      req,
      503,
      "chat",
      Date.now() - started,
      "ai_provider_unavailable",
    );
    return json(
      503,
      apiError(
        "ai_provider_unavailable",
        "FRELUX AI is temporarily unavailable. Retry with backoff.",
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  let raw: string | null = null;
  try {
    raw = await provider.call();
  } catch {
    raw = null;
  }
  if (!raw) {
    await meter(
      auth.key,
      auth.requestId,
      req,
      502,
      "chat",
      Date.now() - started,
      "provider_failure",
      { provider: provider.provider },
    );
    return json(
      502,
      apiError(
        "ai_provider_unavailable",
        "FRELUX AI could not complete this request. Retry with backoff.",
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  let parsed: {
    taskType?: string;
    engineId?: string;
    engineInput?: unknown;
    reply?: string;
    followUpQuestion?: string;
  };
  try {
    parsed = JSON.parse(raw);
  } catch {
    await meter(
      auth.key,
      auth.requestId,
      req,
      502,
      "chat",
      Date.now() - started,
      "provider_failure",
      { provider: provider.provider },
    );
    return json(
      502,
      apiError(
        "ai_provider_unavailable",
        "FRELUX AI returned an unusable response.",
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  // §10: calculation requests MUST go through the canonical
  // engines. The AI proposes an engine intent; the gateway
  // executes the registered engine. Unknown ids are refused —
  // the AI can never fall back to its own math.
  if (parsed.taskType === "calculation") {
    const engineId = typeof parsed.engineId === "string" ? parsed.engineId : "";
    const descriptor = listEngines().find((e) => e.id === engineId);
    if (!descriptor) {
      await meter(
        auth.key,
        auth.requestId,
        req,
        422,
        "chat",
        Date.now() - started,
        "unknown_engine",
        { provider: provider.provider },
      );
      return json(
        422,
        {
          ...apiError(
            "calculation_requires_engine",
            "This request needs a deterministic calculation, but no registered FRELUX engine matches it. FRELUX AI will not fabricate calculation results.",
            auth.requestId,
          ),
          registeredEngines: listEngines().map((e) => e.id),
        },
        auth.requestId,
      );
    }
    const result = await executeEngine(engineId, parsed.engineInput);
    const latency = Date.now() - started;
    await meter(
      auth.key,
      auth.requestId,
      req,
      result.ok ? 200 : 422,
      "chat",
      latency,
      result.ok ? undefined : "validation_failed",
      { provider: provider.provider },
    );
    return json(
      result.ok ? 200 : 422,
      {
        api: "FRELUX AI API",
        version: API_VERSION,
        reply: result.ok
          ? `Calculated by the authoritative FRELUX ${descriptor.title} engine.`
          : "The calculation input is incomplete — FRELUX does not invent missing values.",
        calculation: result.ok
          ? {
              engine: engineId,
              deterministic: true,
              calculatedBy: descriptor.creditedAs,
              result,
            }
          : undefined,
        validation: result.ok
          ? undefined
          : { engine: engineId, details: result.error },
        followUpQuestion: parsed.followUpQuestion ?? undefined,
        requestId: auth.requestId,
      },
      auth.requestId,
    );
  }

  await meter(
    auth.key,
    auth.requestId,
    req,
    200,
    "chat",
    Date.now() - started,
    undefined,
    { provider: provider.provider },
  );
  return json(
    200,
    {
      api: "FRELUX AI API",
      version: API_VERSION,
      reply:
        typeof parsed.reply === "string" && parsed.reply.length > 0
          ? parsed.reply
          : (parsed.followUpQuestion ?? "Please provide more detail."),
      followUpQuestion: parsed.followUpQuestion ?? undefined,
      requestId: auth.requestId,
    },
    auth.requestId,
  );
}

