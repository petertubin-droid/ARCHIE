async function handleMarketPrices(req: Request, auth: AuthedRequest, url: URL) {
  const started = Date.now();
  const product = url.searchParams.get("product")?.trim() ?? "";
  const region = url.searchParams.get("region")?.trim().toUpperCase() ?? null;
  const country = url.searchParams.get("country")?.trim().toUpperCase() ?? "NG";

  if (product.length < 2) {
    return json(
      400,
      apiError(
        "invalid_request",
        "Provide ?product= (at least 2 characters).",
        auth.requestId,
      ),
      auth.requestId,
    );
  }
  if (region && !(await checkPlanRegion(auth.key, region))) {
    await meter(
      auth.key,
      auth.requestId,
      req,
      403,
      "market",
      Date.now() - started,
      "region_not_available_for_plan",
    );
    return json(
      403,
      apiError(
        "region_not_available_for_plan",
        `Region "${region}" is not included in this API key's plan.`,
        auth.requestId,
      ),
      auth.requestId,
    );
  }

  // OBSERVED MARKET PRICE — web intelligence observations that
  // passed verification (Phase 6.5a pipeline). Point-in-time
  // observations, never guaranteed current pricing.
  const { data: observed, error: obsError } = await svc
    .from("frelux_price_observations")
    .select(
      "product_name,price,currency,unit_package,region,country,supplier,url,retrieved_at,source_reliability,confidence,verification_status",
    )
    .eq("verification_status", "VERIFIED")
    .ilike("product_name", `%${product}%`)
    .eq(region ? "region" : "country", region ?? country)
    .order("retrieved_at", { ascending: false })
    .limit(MAX_MARKET_RESULTS);

  // FRELUX CONFIGURED PRICE — the approved market pricing the
  // calculators themselves use (the canonical configuration).
  let configuredQuery = svc
    .from("market_pricing")
    .select(
      "market_code,price_label,price_type,price,currency_code,price_unit,package_size,package_unit,effective_from,pricing_version,source_name,confidence",
    )
    .ilike("price_label", `%${product}%`);
  if (region) configuredQuery = configuredQuery.eq("market_code", region);
  const { data: configured, error: cfgError } =
    await configuredQuery.limit(MAX_MARKET_RESULTS);

  await meter(
    auth.key,
    auth.requestId,
    req,
    200,
    "market",
    Date.now() - started,
    undefined,
    { region: region ?? undefined },
  );

  const failures: string[] = [];
  if (obsError) failures.push("observations");
  if (cfgError) failures.push("configured_prices");

  return json(
    failures.length === 2 ? 503 : 200,
    {
      api: "FRELUX AI API",
      version: API_VERSION,
      query: { product, region, country },
      observedMarketPrices: (observed ?? []).map((o) => ({
        kind: "OBSERVED_MARKET_PRICE",
        ...o,
        disclaimer:
          "Point-in-time observation from a verified web source. Not guaranteed current pricing.",
      })),
      freluxConfiguredPrices: (configured ?? []).map((c) => ({
        kind: "FRELUX_CONFIGURED_PRICE",
        ...c,
      })),
      note: "Prices are labeled by kind. OBSERVED MARKET PRICE ≠ FRELUX CONFIGURED PRICE ≠ ACTUAL PROJECT PRICE — never treat an observed web price as guaranteed current pricing.",
      ...(failures.length > 0
        ? { degraded: `Temporarily unavailable: ${failures.join(", ")}.` }
        : {}),
      requestId: auth.requestId,
    },
    auth.requestId,
  );
}

