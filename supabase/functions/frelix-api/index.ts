// FRELUX PHASE 7 — THE OFFICIAL FRELUX AI API GATEWAY
//
// One edge function serves the entire versioned public API:
//   /v1                      — FRELUX API identity
//   /v1/capabilities         — implemented, tested capabilities
//   /v1/plans                — configurable plans (monetization)
//   /v1/calculators/:engine  — CANONICAL deterministic engines
//   /v1/chat                 — FRELUX AI (provider-independent)
//   /v1/market/prices        — observed vs configured prices
//   /v1/regions[/:code]      — regional construction profiles
//   /v1/feedback             — USER_PROVIDED learning candidate
//   /v1/usage                — this key's metered usage
//   /v1/keys[...]            — self-service key management (JWT)
//
// Security (Phase 7 §21):
//   * FLX- keys only; hash lookup via service role — raw keys
//     are never stored, logged, or echoed
//   * tenant ALWAYS resolved from the key record — client
//     identity fields are never trusted
//   * status/revocation/expiry, per-minute rate limit, daily/
//     monthly quotas, capability allow-list, plan region
//     entitlement — all evaluated server-side
//   * request-size limits, structured errors, metering rows
//     store metadata only (no request content)
//   * no user-supplied URL is ever fetched (no SSRF surface);
//     chat treats user text as DATA — tool intents are limited
//     to registered engine ids (no prompt-injection escape)
//   * API feedback enters the learning pipeline as CANDIDATE —
//     USER_PROVIDED ≠ SYSTEM_VERIFIED ≠ APPROVED (no bypass)
//
// The deterministic engines come from the canonical registry
// bundle (_engines.bundle.js — generated by
// `npm run build:api-engines`, re-exporting
// src/lib/ai-foundation/engines-registry.ts). The gateway has
// NO calculation math of its own and invents no missing values:
// incomplete inputs get structured validation responses.
// =========================================================

