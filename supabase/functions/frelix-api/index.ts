serveWithCors(async (req: Request) => {
  // Audit fix M-7 (2026-09-11): rate limit this endpoint per user
  // (falls back to client IP). OPTIONS preflights are answered at
  // the CORS boundary and never reach this check.
  const rl = checkRateLimit(
    getRateLimitKey(req, req.headers.get("x-user-id") ?? undefined),
    RATE_LIMITS.AI,
  );
  if (!rl.allowed) return rateLimitedResponse(rl.resetAt);

  const requestId = crypto.randomUUID();
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });

  const url = new URL(req.url);
  const path = url.pathname.replace(/^.*frelix-api\//, "/");

  try {
    // Public discovery endpoints — FRELUX identity only.
    if (req.method === "GET" && (path === "/v1" || path === "/v1/"))
      return handleIdentity(requestId);
    if (req.method === "GET" && path === "/v1/capabilities")
      return handleCapabilities(requestId);
    if (req.method === "GET" && path === "/v1/plans")
      return handlePlans(requestId);

    // Key management — session JWT (never an API key).
    if (path === "/v1/keys" || path.startsWith("/v1/keys/")) {
      return await handleKeys(req, path, requestId);
    }

    // API-key-authenticated surface.
    const calcMatch = /^\/v1\/calculators\/([a-z0-9_]+)$/.exec(path);
    const capability =
      req.method === "POST" && path === "/v1/chat"
        ? "chat"
        : calcMatch
          ? "calculators"
          : req.method === "GET" && path === "/v1/market/prices"
            ? "market"
            : req.method === "GET" &&
                (path === "/v1/regions" || path.startsWith("/v1/regions/"))
              ? "regions"
              : req.method === "POST" && path === "/v1/feedback"
                ? "feedback"
                : req.method === "GET" && path === "/v1/usage"
                  ? "usage"
                  : null;

    if (!capability) {
      return json(
        404,
        apiError(
          "not_found",
          `Unknown endpoint. See /${API_VERSION}/capabilities.`,
          requestId,
        ),
        requestId,
      );
    }

    const started = Date.now();
    const { auth, denial } = await authenticate(req, requestId, capability);
    if (denial || !auth) return denial!;

    if (calcMatch) return await handleCalculator(req, auth, calcMatch[1]);
    if (capability === "chat") return await handleChat(req, auth);
    if (capability === "market")
      return await handleMarketPrices(req, auth, url);
    if (capability === "regions") {
      const regionMatch = /^\/v1\/regions\/([A-Za-z]{2})$/.exec(path);
      return await handleRegions(req, auth, regionMatch?.[1]);
    }
    if (capability === "feedback") return await handleFeedback(req, auth);
    if (capability === "usage") return await handleUsage(req, auth);
    void started;
    return json(
      404,
      apiError("not_found", "Unknown endpoint.", requestId),
      requestId,
    );
  } catch (error) {
    // Never leak internals or secrets in error responses.
    void error;
    return json(
      500,
      apiError(
        "internal_error",
        "FRELUX API could not complete this request. Retry with backoff.",
        requestId,
      ),
      requestId,
    );
  }
});
