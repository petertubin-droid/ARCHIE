async function getJwtUser(authHeader: string | null): Promise<string | null> {
  const token = extractBearerToken(authHeader);
  if (!token || token.startsWith("FLX-")) return null;
  const userClient = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
    auth: { persistSession: false, autoRefreshToken: false },
    global: { headers: { Authorization: `Bearer ${token}` } },
  });
  const { data } = await userClient.auth.getUser(token);
  return data?.user?.id ?? null;
}

async function handleKeys(
  req: Request,
  path: string,
  requestId: string,
): Promise<Response> {
  const userId = await getJwtUser(req.headers.get("Authorization"));
  if (!userId) {
    return json(
      401,
      apiError(
        "unauthorized",
        "Key management requires an authenticated FRELUX user (Bearer session token).",
        requestId,
      ),
      requestId,
    );
  }
  const userClient = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
    auth: { persistSession: false, autoRefreshToken: false },
    global: {
      headers: {
        Authorization: `Bearer ${extractBearerToken(req.headers.get("Authorization"))}`,
      },
    },
  });

  // POST /v1/keys — create
  if (path === "/v1/keys" && req.method === "POST") {
    const { body, error } = await readJson(req);
    if (error) return error;
    const name = typeof body.name === "string" ? body.name.trim() : "";
    if (name.length < 1 || name.length > 100) {
      return json(
        400,
        apiError(
          "invalid_request",
          '"name" must be 1–100 characters.',
          requestId,
        ),
        requestId,
      );
    }
    const rawKey = generateFreluxApiKey(); // §3: crypto-random, exactly 32 chars
    const keyHash = await hashApiKey(rawKey);
    // API GOVERNANCE: capabilities, scopes and quotas come
    // from the plan the OWNER/ADMIN configured in
    // frelux_api_plans — NEVER from the request body. A
    // subscriber can never self-issue elevated permissions.
    const { data: plan } = await svc
      .from("frelux_api_plans")
      .select("key,config,active")
      .eq("key", "free")
      .maybeSingle();
    if (!plan?.active) {
      return json(
        503,
        apiError(
          "key_creation_failed",
          "No active plan is configured. Contact the FRELUX owner.",
          requestId,
        ),
        requestId,
      );
    }
    const planCfg = (plan.config ?? {}) as {
      capabilities?: string[];
      permissions?: string[];
      rateLimitPerMinute?: number;
      dailyQuota?: number;
      monthlyQuota?: number;
    };
    const insert = {
      name,
      key_prefix: apiKeyDisplayPrefix(rawKey),
      key_hash: keyHash,
      permissions:
        Array.isArray(planCfg.capabilities) && planCfg.capabilities.length > 0
          ? planCfg.capabilities
          : Array.isArray(planCfg.permissions) && planCfg.permissions.length > 0
            ? planCfg.permissions
            : ["calculators"],
      plan_key: "free",
      rate_limit_per_minute: Math.max(1, planCfg.rateLimitPerMinute ?? 30),
      daily_quota: Math.max(1, planCfg.dailyQuota ?? 100),
      monthly_quota: Math.max(1, planCfg.monthlyQuota ?? 2500),
      expires_at: null,
    };
    const { data, error: insertError } = await userClient
      .from("frelux_api_keys")
      .insert(insert)
      .select(
        "id,name,key_prefix,status,plan_key,rate_limit_per_minute,daily_quota,monthly_quota,expires_at,created_at",
      )
      .single();
    if (insertError || !data) {
      return json(
        503,
        apiError(
          "key_creation_failed",
          "The key could not be created. Retry.",
          requestId,
        ),
        requestId,
      );
    }
    return json(
      201,
      {
        ...data,
        key: rawKey, // shown exactly once — never stored raw, never retrievable again
        warning:
          "Store this key now. FRELUX stores only a hash — it cannot be shown again.",
        requestId,
      },
      requestId,
    );
  }

  // GET /v1/keys — list (masked)
  if (path === "/v1/keys" && req.method === "GET") {
    const { data, error } = await userClient
      .from("frelux_api_keys")
      .select(
        "id,name,key_prefix,status,permissions,plan_key,rate_limit_per_minute,daily_quota,monthly_quota,expires_at,last_used_at,request_count,created_at,updated_at",
      )
      .order("created_at", { ascending: false });
    if (error) {
      return json(
        503,
        apiError("internal_error", "Keys could not be listed.", requestId),
        requestId,
      );
    }
    return json(200, { keys: data, requestId }, requestId);
  }

  // /v1/keys/:id[/rotate]
  const keyMatch = /^\/v1\/keys\/([0-9a-fA-F-]{36})(\/rotate)?$/.exec(path);
  if (!keyMatch) {
    return json(
      404,
      apiError("not_found", "Unknown endpoint.", requestId),
      requestId,
    );
  }
  const keyId = keyMatch[1];

  if (keyMatch[2] === "/rotate" && req.method === "POST") {
    const rawKey = generateFreluxApiKey();
    const keyHash = await hashApiKey(rawKey);
    const { data, error: updateError } = await userClient
      .from("frelux_api_keys")
      .update({
        key_hash: keyHash,
        key_prefix: apiKeyDisplayPrefix(rawKey),
        status: "active",
        updated_at: new Date().toISOString(),
      })
      .eq("id", keyId)
      .select("id,name,key_prefix,status")
      .single();
    if (updateError || !data) {
      return json(
        404,
        apiError("not_found", "Key not found (or not yours).", requestId),
        requestId,
      );
    }
    return json(
      200,
      {
        ...data,
        key: rawKey,
        warning: "Store this new key now — the old secret no longer works.",
        requestId,
      },
      requestId,
    );
  }

  if (req.method === "PATCH") {
    const { body, error } = await readJson(req);
    if (error) return error;
    const update: Record<string, unknown> = {
      updated_at: new Date().toISOString(),
    };
    if (typeof body.name === "string" && body.name.trim().length >= 1)
      update.name = body.name.trim();
    // API GOVERNANCE: subscribers can NEVER alter their own
    // permissions, plan, quotas, rate limits or expiry through
    // this route. Those are Owner/Admin-configured only (the
    // Admin API Keys console; RLS blocks client writes too).
    // This route accepts ONLY name and status changes.
    const { data, error: updateError } = await userClient
      .from("frelux_api_keys")
      .update(update)
      .eq("id", keyId)
      .select(
        "id,name,key_prefix,status,permissions,plan_key,rate_limit_per_minute,daily_quota,monthly_quota,expires_at,updated_at",
      )
      .single();
    if (updateError || !data) {
      return json(
        404,
        apiError("not_found", "Key not found (or not yours).", requestId),
        requestId,
      );
    }
    return json(200, { ...data, requestId }, requestId);
  }

  if (req.method === "DELETE") {
    const { data, error: updateError } = await userClient
      .from("frelux_api_keys")
      .update({ status: "revoked", updated_at: new Date().toISOString() })
      .eq("id", keyId)
      .select("id,name,status")
      .single();
    if (updateError || !data) {
      return json(
        404,
        apiError("not_found", "Key not found (or not yours).", requestId),
        requestId,
      );
    }
    return json(
      200,
      {
        ...data,
        note: "Key revoked. It will be refused on all future requests.",
        requestId,
      },
      requestId,
    );
  }

  return json(
    405,
    apiError("method_not_allowed", "Method not allowed.", requestId),
    requestId,
  );
}

