## Introduction

Screeding looks forgiving — mix, spread, smooth — and that illusion is exactly why so many walls end up sanded back to bare block. The mistakes repeat across Nigerian sites with remarkable discipline: screeding over dust, mixing by eye, curing in direct sun, and calling a wall "ready for paint" while it is still chemically alive.

This guide takes the most common screeding failures one at a time, explains the mechanism behind each so you can recognize its early signs on your own wall, and gives the specific practice that prevents it. Every fix here costs nothing but attention — the mistakes cost entire redo cycles.

## Mistake 1 — Screeding Over Dust

**The scene:** the wall is brushed with a broom, the mix goes up, the job looks finished.

**The mechanism:** screed bonds by mechanical and chemical grip on the surface. A film of dust — block-cutting fines, construction dust, the Sahara's harmattan contribution — sits between screed and wall as a slip layer. The screed cures perfectly; it simply cures onto dust instead of onto blockwork.

**The early sign:** fresh screed that lifts at edges within days; a tap test that drums in patches (dust is never evenly distributed). Six months later the same patches sound hollow, and everyone blames the "mix" — the mix was fine; the surface was never there.

**The prevention:** wash or at minimum damp-wipe the wall the day before (allowing it to reach surface-dry by application), never dry-broom and proceed. The ten litres of water is the cheapest bonding agent on the market.

## Mistake 2 — Mixing by Eye and Feel

**The scene:** "we have been doing this for twenty years" — cement and sand shovelled by judgement, water added until the mix "looks right."

**The mechanism:** the ratio controls paste-coating and void-filling; the water controls the voids. Both drift batch to batch when eyeballed, and the wall becomes a patchwork of lean, rich, wet, and dry sections — with each section's failure mode on display within the year: dusting where lean, cracking where rich, soft where over-watered. (The full chemistry is in [the mix ratios guide](/learn/cement-sand-ratio-screeding-explained).)

**The early sign:** colour and texture differences between batches visible in raking light even under paint; the squeeze test failing identically two batches running.

**The prevention:** level head-pans, counted per batch, ratio chalked at the mixer, water to the squeeze test in stages. Twenty years of experience is worth exactly nothing per batch — the counting is worth everything.

## Mistake 3 — One Thick Hero Coat

**The scene:** a wall needing 12–15 mm gets it in a single pass, "to save time."

**The mechanism:** thick cement-based passes shrink as they cure — the thicker the pass, the more absolute shrinkage, and shrinkage in a restrained coat becomes crack energy. Beyond roughly 12–15 mm, one-coat screed maps and crazes with a reliability that has ended many a contractor's bonus.

**The early sign:** hairline mapping appearing within days of a "perfect" finish, always worst in the thickest sections.

**The prevention:** coats matched to purpose — levelling passes ruled to staffs, then finishing passes thin where hardness matters; deep hollows filled and allowed to stiffen (or cure, if deep) before the plane work runs over them. The "saved time" costs the re-do.

## Mistake 4 — Curing in Direct Sun

**The scene:** the wall is screeded by 10 am, the sun hits it by noon, and everyone moves to the next room.

**The mechanism:** cement hydrates using the mix's water. Sun and moving air strip surface moisture before hydration completes — the surface is literally starved of its chemistry while it looks like it is drying "nicely." The result dusts under a thumb, crazes, and takes paint badly — a wall that finished itself before it made itself.

**The early sign:** a pale, powdery surface that wasn't there the evening before; a thumb that comes away dusty.

**The prevention:** the 3–7 day damp cure — mist morning and evening, hessian or polythene on the sun-side, work shaded faces by the clock, and in harmattan double the misting. The water costs nothing; the sun damage costs the whole surface. (See [the curing and drying guide](/learn/curing-drying-times-screeded-walls).)

## Mistake 5 — Painting a Chemically Alive Wall

**The scene:** the wall looks dry on day three, the painter is on site, the client wants the room done.

**The mechanism:** "dry" and "cured" are different dates. A screed's moisture leaves the surface first and the depth last; paint applied over that residual moisture traps it, and the moisture exits through the film as blisters, peeling patches, and the corner-stain cycles that owners repaint annually for years.

**The early sign:** none visible — which is the point. The overnight polythene test shows the moisture that the eye cannot.

**The prevention:** the paint schedule keyed to the *test*, not the touch: polythene taped to the wall overnight, dry at dawn, painting proceeds; condensation, painting waits. The calendar loses to the test every time.

## Mistake 6 — Skipping the Assessment on "Fair" Walls

**The scene:** the wall looks decent, so Stage 0 is skipped as a formality.

**The mechanism:** "fair" hides three failure seeds: drummy patches (old render letting go), paint or smoothing layers that repel new screed, and deviations beyond what a standard coat can absorb. Each seed matures under the new coat, exactly where it cannot be reached.

**The early sign:** localised defects in a wall that is otherwise sound — the assessment skipped is visible as a map of exactly what it missed.

**The prevention:** the four tests on every wall regardless of looks — tap, splash, straightedge, polythene. The twenty minutes is the cheapest insurance in the trade (see [the complete workflow](/learn/complete-guide-wall-screeding-professional)).

## Mistake 7 — The Untested Bond on Smooth Surfaces

**The scene:** screed applied over smooth concrete, old paint, or a previous coat, "because screed sticks to everything."

**The mechanism:** screed keys into open pores and mechanical tooth. Smooth, painted, or burnished surfaces offer neither — the bond is whatever chemical adhesion the mix can summon alone, which is not enough. The coat that "seemed fine" at handover becomes the sheet that peels in sections after the first thermal cycle.

**The early sign:** edges of the new coat lifting where it meets windows or corners — the places stress concentrates first.

**The prevention:** hack or scarify smooth faces, or use a bonding agent per [the bonding agents guide](/learn/best-bonding-agents-wall-screeding) — chosen for the surface, applied per its instructions, and never "a splash in the mix for luck."

## Mistake 8 — No Acceptance Checks Before Paint

**The scene:** the wall is pronounced finished by the crew, the painter follows immediately.

**The mechanism:** whatever the checks would have found — hollows, ripple, dusting, deviation — now lies under primer and two coats, and every repair after that point costs the paint as well as the screed. Paint is the most expensive coat a screed defect will ever wear.

**The early sign:** the finisher's "it's done" arriving without a straightedge, torch, or tap anywhere in sight.

**The prevention:** the five-check acceptance before paint — straightedge, torch, palm, tap, moisture (the protocol is in [the complete guide](/learn/complete-guide-wall-screeding-professional)) — written in the site book with a date. Payment follows the checks; everything else follows payment.

## The Pattern — and the Prevention That Costs Nothing

Read down the list and one sentence explains it: **every mistake is invisible exactly when it is cheapest to prevent, and bills when it is most expensive to discover** — usually to the next coat, the next season, or the next owner. And every prevention is attention, not money: wash water, level pans, staffs, misting, a polythene square, a straightedge, and a dated site book. The professional screeder's advantage is not a better mix; it is that they check, count, cure, and test — the four habits that turn the same materials into a wall that lasts. (For the surface failures that show up later and how to repair them, see [the finishing defects guide](/learn/common-finishing-defects-and-how-to-fix); for the quantities that keep the redoing cheap to avoid, [the quantities guide](/learn/how-to-calculate-screeding-material-quantities).)


## The Redo Ledger — What One Mistake Actually Costs

The redo arithmetic, for the wall that taught the lesson the expensive way: a 30 m² bedroom wall screeded over dust, hollow by month six. The direct bill is the re-do itself — cut back the failed coat (labour), re-prep *properly this time* (the wash the wall should have had), re-screed at a full day's labour, re-cure for the week the sun stole the first time. But the honest ledger keeps counting: the paint that came off with the failed coat, re-primed and re-coated; the room's joinery and finishes worked around, protected, and cleaned after; and the calendar — the room out of service for a second cycle because the first cycle saved ten minutes.

Set against it, the prevention for that mistake: one bucket of wash water, on day one. The ratio between prevention and cure on this single wall runs above a hundred to one, and the same ratio holds for the pan-count that prevents dusting, the misting that prevents crazing, and the polythene square that prevents a paint failure — attention is the only material in construction that trades at that price.

The other half of the ledger is *whose* mistake it was: on most sites, the labourer made the mistake, the supervisor failed to check it, and the owner paid for both. The site book habit distributes the ledger honestly — the check that would have caught the dust pass costs the supervisor a minute and saves the owner the redo, which is why the checklist (not the goodwill) is the actual quality system on a supervised site.

## Closing

The eight mistakes share one cure: discipline at the moments the eye cannot audit — a washed wall, a counted batch, a thin-enough coat, a misted cure, a polythene test, and a straightedge with the courage to fail a wall. None of it costs money or skill; all of it costs less than one redo cycle, and one redo cycle is what each of these mistakes is quietly scheduling on your site this week.
