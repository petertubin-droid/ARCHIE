## Introduction

A bathroom tile job is two projects pretending to be one: a water management system wearing a decorative surface. When the waterproofing is right, nobody thinks about it for twenty years. When it is wrong, the neighbour downstairs thinks about it every day.

This guide covers the sequence professionals follow for wet-area tiling in Nigerian bathrooms: substrate assessment, the waterproofing membrane stage that must precede any tile, falls and drainage slopes, tile selection for wet surfaces, and the fixing and grouting details that keep water out of the wall assembly — not just off its surface.

## Why Waterproofing Comes Before Tiling

Grout is not waterproof. Neither is tile adhesive, and neither is the tile itself — ceramic absorbs a small but real percentage of water, and every joint in the installation is a slow lane for moisture. A bathroom without a membrane relies entirely on grout lines holding back water, and grout is designed to be flexible and cleanable, not to be a water barrier.

The failure sequence is predictable. Water enters through tiny gaps at joints and penetrations, migrates behind the tiles, saturates the screed and blockwork, and begins to work outward — stains on the far side of the wall, paint bubbling on the ceiling below, a persistent damp smell that no amount of cleaning removes. By the time it is visible, the tiling has to come off, the wall has to dry out for weeks, and the repair costs several times what a membrane would have cost on day one.

Waterproofing applied under the tiles is invisible, permanent, and inexpensive relative to the damage it prevents. That asymmetry — small cost, invisible when correct, catastrophic when absent — is why every serious wet-area specification puts the membrane first.

## How Water Actually Moves in a Bathroom

Two mechanisms, and they need different answers:

**Direct wetting.** Shower spray, splashes at the basin, water running across the floor to the drain. This is bulk water moving under gravity, and it is managed by geometry: slopes that carry water to the drain and surfaces that shed it rather than pond it.

**Vapour.** Warm, humid air from showers condenses on cooler surfaces and works into joints as vapour, including through grout. Vapour is managed by the membrane's continuity — it does not need thickness so much as it needs to have no gaps.

A professional waterproofing job answers both. The geometry (falls, drain position, junction details) handles bulk water; the continuous membrane handles whatever gets past the surface, including vapour.

## Assessing the Substrate First

The membrane goes onto the structure that will sit under it for decades, so it inherits every flaw that structure has. Before any waterproofing product is opened:

**Check the screed.** Bathroom floors are screeded to create the fall to the drain. The screed must be cured (typically 7 days minimum, dry through), sound — no hollow areas or dusty surface — and correctly sloped. A membrane over a weak screed is a raincoat on a rotting frame.

**Verify the fall.** The industry standard is a fall of roughly 1:100 to 1:80 — 1 cm of drop per metre of run — directing water to the drain from every part of the floor. Check it with a spirit level in several directions before tiling; a flat bathroom floor is a defect, not a feature.

**Look at the walls.** Blockwork should be plastered flush and true, corners square, and any plumbing chases filled solid. Movement cracks in fresh plaster will telegraph through the membrane, so plaster should be fully cured first.

**Plan the penetrations.** Every pipe that passes through a floor or wall — the drain itself, the shower mixer, the basin wastes — is a potential leak point that needs specific detailing, not just a hole in the membrane.

## The Waterproofing System: Applying the Membrane

Liquid-applied membranes — polymer-modified cementitious coatings, common in the Nigerian market in 5 kg and 20 kg kits — are the standard choice for bathroom work. They are applied like thick paint and cure into a seamless, flexible barrier. The application sequence matters more than the brand:

1. **Prime if the product requires it.** Some membranes bond directly to dampened concrete; others need a primer. Follow the data sheet — this is the one place in tiling where the instructions genuinely cannot be improvised.
2. **Detail first, then field.** Corners, wall-floor junctions, and pipe penetrations get reinforced with the manufacturer's sealing tape or fabric mats embedded in the first coat. These are the highest-risk points in the whole bathroom; they fail first and worst when skipped.
3. **Apply the first coat** with a brush or roller over the full wet zone, working the membrane into the surface rather than simply painting over it. Let it cure to the manufacturer's stated time — typically a few hours until it changes colour or is touch-dry.
4. **Apply the second coat at right angles** to the first. Two thin coats outperform one thick one, and the cross-direction application closes pinholes.
5. **Extend past the wet zone.** The membrane should run up the walls to at least the wetted height and across the floor of the whole room, not just the shower footprint — water travels.

Wet zone heights, applied as a minimum:

| Zone | Waterproofing height |
|---|---|
| Shower area walls | Full wetted height, minimum 1800 mm, ideally to ceiling |
| Around bath rim | 600 mm above the rim, plus the full vertical of tap wall |
| Basin splash wall | 1200 mm from floor behind the fixture |
| Entire floor | Full room, extending 150 mm up the walls at junctions |

## Tiling Over the Membrane Without Damaging It

The membrane's weakest moment is between application and tiling. It is now a continuous barrier — and a thin one, easily punctured by dropped tools, dragged tile boxes, and careless scaffold legs. Professional tilers keep the finished membrane floor covered with cardboard or hardboard until the first tile goes down.

Use a suitable tile adhesive over the membrane: cement-based adhesives labelled as flexible or polymer-modified bond over the coating's surface without attacking it. Avoid solvent-based contact adhesives over liquid membranes — solvents and membranes are a bad chemical marriage. The tile choice matters too: in shower areas, low-absorption tiles (porcelain, or glazed ceramic rated for wet use) keep the assembly dry behind them; highly absorbent unglazed tiles in a steamy shower work against even a good membrane.

Grout joints in wet areas should be kept reasonably narrow (2–3 mm) and full — voids in grout are reservoirs. For the full grout selection logic, see [our grout selection and application guide](/learn/tile-grout-selection-and-application).

## The Sealant Layer: Where Tiles Meet Everything

The joints where floor meets wall, where the shower screen sits, and around every penetration are not grout joints — they are movement joints, and they get silicone sealant, not grout. Grout in a moving joint cracks within months; a good sanitary silicone flexes with the movement and stays watertight.

The rule is simple: rigid materials meet flexible ones, and flexible ones get sealant. Tile-to-tile inside a plane: grout. Tile to tub, tile to floor junction, tile to drain frame, tile to pipe: colour-matched sanitary silicone, tooled into the joint, on a clean dry surface. This single detailing habit prevents a disproportionate share of bathroom leaks.

## Flood-Testing Before the Tiles Go On

The professional's proof that the membrane works is a flood test (ponding test). Block the drain, flood the waterproofed floor with 2–3 cm of water, mark the waterline, and wait 24–48 hours. If the level holds, the membrane is continuous; if it drops, there is a breach, and finding it now costs a brush stroke while finding it under tiles costs a demolition.

New builds on concrete slabs can be tested this way as standard. In occupied renovations above other units, a 24-hour flood test is not optional caution — it is the moment the downstairs neighbour's ceiling is protected or condemned.

## Common Waterproofing Failures and Their Causes

**Membrane punctured during tiling.** Cause: no protection layer over the cured coating. Prevention: hardboard until tiles cover the floor.

**Leak at the drain.** Cause: the membrane not dressed into the drain clamping ring or collar. Prevention: use a proper drain flange designed for the membrane to clamp into, and detail it before the field coats.

**Tile falling off shower wall years later, soaked behind.** Cause: membrane only on the floor, walls trusted to grout. Prevention: full-height wet-zone treatment per the table above.

**Stains on the wall outside the bathroom.** Cause: splashed water finding the one unsealed penetration. Prevention: sealant layer at every penetration, checked annually.

**Grout cracking at the wall-floor junction then leaking.** Cause: grout used where the assembly moves. Prevention: movement joints get silicone, always.

## Maintenance That Preserves the System

A waterproofed bathroom still asks for ten minutes of attention a year:

- Inspect silicone joints for cracks or lifting — re-seal any suspect joint before it leaks, not after
- Check grout for cracks and voids, especially in the shower; a grout refresh costs little, water behind grout costs a re-tile
- Keep the drain clear — ponding from a slow drain forces water to sit and find weak points
- Avoid abrasive cleaners on silicone lines; they score the surface and let mould take hold
- Reseal natural stone tiles on their maintenance schedule if stone is used

## Conclusion

Waterproofing a bathroom is the discipline of doing invisible work correctly before the visible work begins: a sound, sloped substrate; a continuous membrane with taped corners and dressed penetrations; a flood test that proves it; tiles and adhesive compatible with the membrane; silicone at every movement joint; and a yearly ten-minute inspection of the joints that flex.

None of it is difficult, and almost all of it is cheap compared to the failure it prevents. If you are budgeting a bathroom, the waterproofing line item is the one place not to economise — for the quantities and costs of the tiling layer above it, run your figures through the [tile calculator](/tile-calculator) and the [tile cost estimation guide](/learn/tile-cost-estimation-materials-labour-budget).
