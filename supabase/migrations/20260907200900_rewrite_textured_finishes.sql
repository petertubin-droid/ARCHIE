## A Worked Example — One Facade in Tyrolene

A single-storey bungalow frontage: 9 m wide × 3.2 m high, minus a door and two windows — roughly 24 m² of net face, west-facing, with typical hand-render ripple and two hairline movement cracks at the corners.

**The sequence as it should run:** crack treatment first (the hairlines are cut, filled with flexible exterior filler — because rigid filler under texture re-cracks and the texture cannot hide a crack that moves); wash-down and algae treatment at the shaded base; two days of damp-curing-friendly weather chosen; then the tyrolene applied in two passes over the whole face in one session, worked from scaffold height downward so spatter falls onto fresh texture, not finished texture.

**The checkpoints:** a sample panel beside the gate, kept until the end (the agreed texture size lives on it, and any dispute about "too coarse" or "too fine" is settled against it); the stand-off distance and mix kept consistent per bay; and the day chosen with the forecast — a tyrolene face washed by rain within hours becomes a stripped-and-again job.

**What it costs in honest terms:** tyrolene consumes material by weight per square metre far beyond paint, and the labour is machine-paced but consistency-priced — the whole facade's look lives or dies on the operator keeping the same distance, pressure, and mix for the entire session. That is why the sample panel, not the brochure, is the specification.

