## Maintaining Texture — the Ownership Part

Texture maintenance differs from paint maintenance in three ways:

- **Dust and growth:** textured exteriors hold dust and host algae in their relief; an annual wash (soft brush, low pressure) keeps the film healthy and the colour true. Skipped for years, the wash becomes a treatment.
- **Repairs:** a damaged texture patch is repaired by re-texturing the patch and blending a larger surrounding area — the pattern must be rebuilt, not painted in. Tyrolene patches well (re-splatter blends); stamped and skip-trowel patterns patch poorly (the hand and pattern rarely match).
- **Repainting:** cement-based textures take repaints over their lifetime — but the repaint is a texture repaint, with rollers that reach into the relief, not a flat-wall roller pass. Budget accordingly: textured walls consume noticeably more paint per square metre than smooth ones.

## Closing

Texture is deliberate: chosen for the wall's duty and the room's design, applied from a sample panel, and maintained as a texture — never mistaken for paint that went wrong. Choose it where it serves, keep smooth where it would fight, and treat the pattern as the specification — sample panel first, one session per wall, and the forecast consulted before the machine comes out. A texture chosen that way looks intentional in year one and still looks intentional in year ten, which is the only review that matters. For the building-up and repair of the surfaces beneath texture, see the [complete guide to interior wall finishing](/learn/complete-guide-interior-wall-finishing).
