## Introduction

Ask for "wall finishing" at a Nigerian building materials market and you will be asked a follow-up question: skim coat, putty, or direct paint? They are three different products with three different costs, lifespans, and surface outcomes — and much confusion in the trade comes from treating them as interchangeable.

This guide explains what each material actually is, the wall condition each one is designed for, how they are applied, and what they cost per square metre. By the end you will know exactly which system your walls need instead of guessing at the counter.

## The Short Answer

These three materials are not competitors — they are layers in one system, and mature walls usually need two or all three of them:

- **Skim coat** builds trueness. It corrects ripples, hollows, and trowel marks up to about 3 to 5 mm. It is the structural work of a smooth wall.
- **Putty** builds perfection. It fills pinholes and hairline pores after sanding, in scrapes thinner than 2 mm. It is the cosmetic work.
- **Paint** is the finish itself — colour and sheen, over a sealed surface.

Choosing "one of the three" is the wrong question; the right one is which layers your wall actually needs, starting from its condition. A wall that receives all three when it needed two wastes money; a wall that receives one when it needed three wastes the paint twice over — once at purchase, once at peeling.

## Skim Coat — The Levelling Layer

### What it is

A thin finishing coat, 2 to 5 mm, whose job is a flat, true surface rather than strength. Two families dominate the Nigerian market:

| | Cement-based skim | Gypsum skim (pre-mixed bags) |
|---|---|---|
| Composition | Cement + fine sieved plaster sand | Gypsum powder, bagged, just add water |
| Mix control | You control the ratio and sand quality | Factory-controlled, consistent |
| Finish | Very good with skilled application | Excellent, whiter and finer |
| Setting | Slower; needs damp curing in heat | Fast setting; simply dries |
| Best for | Budget jobs, damp-prone walls, bulk areas | Interior walls, speed, uniform results |
| Watch out for | Shrinkage if over-thick; sand quality varies | Sets in the bucket in minutes; not for wet areas |

The cement version is mixed on site — typically a lean mix of cement with the finest, sieved plaster sand, wet enough to trowel but stiff enough to hold. Its quality lives and dies on the sand: pit-run sand with visible grain will tear at every stroke, while washed, sieved plaster sand behaves like a different material. The gypsum version arrives in bags with the chemistry pre-measured; you add water, get a smooth paste, and have a short working window before the set begins.

### When the wall needs it

Run a straightedge over the plaster: gaps over about 2 mm under the rule mean paint alone will memorialise the ripples rather than hide them. Anywhere the hand feels a ridge, the wall wants a skim. The tap test matters too: a skim is a finishing layer, and if the plaster beneath is hollow-sounding, that patch needs cutting out and re-plastering before any skim touches the wall. The [skimming versus plastering guide](/learn/skimming-vs-plastering-understanding-options) draws the full decision line.

### How it goes on

Mixed to a trowel-firm paste, applied with a steel trowel in two thin passes (never one thick one), the second pass flattening at a shallower blade angle, every section boundary feathered so no ridge survives under a fingernail. Cement skims then get 2 to 3 days of damp curing in hot weather; gypsum skims dry through in roughly 24 to 48 hours, then sand.

The two-pass rule is worth internalising, because it is the counter-intuitive one: doubling the number of passes saves time and material. One thick pass shrinks as it dries, and shrinkage means map-cracks, edge ridges, and a sanding stage that cannot undo what chemistry has already cracked through. Two passes at half the thickness each, with a short firming gap between, yield a flatter wall with less total material and dramatically less sanding.

## Putty — The Pore Filler

### What it is

A very fine, creamy paste — gypsum or acrylic-based — sold in tubs and small bags. It contains no coarse particles; its entire purpose is the last sub-millimetre of surface. Where skim builds geometry and putty builds texture, primer (covered below) builds adhesion — and the three are frequently confused at the point of purchase because they all arrive as white paste in a container.

### When the wall needs it

After the skim (or bare plaster) has been sanded, two defects remain that paint will emphasise: **pinholes** — tiny air voids from the skim stage — and **sand-scratches** — the fine parallel scoring left by even good abrasive work. If the raking light shows texture, putty is the answer. On new hand-plastered walls, that is almost always the case; on rare machine-finished backgrounds, putty may genuinely be skippable.

### How it goes on

One thin, scraped pass with a wide flex knife (300 to 400 mm), let dry, sand flush with fine grit, remove dust. It must be thin: putty buried deeper than about 2 mm shrinks, cracks, and pops out in flakes. Bigger defects belong to the skim stage, not the putty tub.

### The mistake that costs most

Painting straight over an un-puttied skim. The first coat of paint sinks into every pinhole, and the second coat frames them in sheen. One putty pass before primer prevents a full repaint later. It is the cheapest hour in the entire finishing sequence relative to what it protects — a 20 kg tub covers a whole room's pinholes and costs a fraction of the paint it saves.

## Direct Paint — When Nothing Between Is Needed

### What it is

Primer (or sealer) plus two to three topcoats applied straight onto plaster.

### When it genuinely works

Only on the best backgrounds: machine-finished or genuinely well-hand-trowelled plaster with deviations under about 1 to 2 mm, fully cured (28 days or more) and dry. In that case a primer to equalise suction plus two quality coats is a legitimate, economical finish — and any skim on top would be wasted money.

### When it is a false economy

Hand plaster almost always carries ripples. Two coats of paint do not level — they tint what is there. Direct paint over mediocre plaster is the most common "saving" in Nigerian finishing, and the most visible one in every evening's raking light. The failure mode is quietly cruel: the paint job looks acceptable on completion day, photographs fine, and then someone hangs a bulb in the corner and the wall shows its history in shadows.

## Primer — The Fourth Player Nobody Budgets

Whichever route you take, primer is not optional: it equalises suction, bonds the coats above to the surface, and evens out sheen. On new skim and putty, use a sealer primer or the paint manufacturer's stated first-coat dilution; on previously painted walls, prime every repaired or sanded-through patch at minimum. Skipping primer saves one coat of cost and repays it with patchy sheen that no number of extra topcoats fixes.

Primer also functions as the final rehearsal stage: over its uniform flat film, every remaining ripple, ridge, and pinhole stands out for the last cheap fix. Professionals inspect the primed wall with a torch before the first topcoat, because primer is the last moment the wall can be corrected without consequences.

## What Each System Delivers — and Costs

Approximate relative economics per square metre of interior wall (materials only, order-of-magnitude, Nigerian market):

| System | Coats | Relative material cost | Surface result |
|---|---|---|---|
| Direct paint on good plaster | 1 primer + 2 paint | Base | Good where background is good |
| Putty + paint | 1 putty + 1 primer + 2 paint | Base + a little | Even, pore-free |
| Skim + putty + paint | 1–2 skim + 1 putty + 1 primer + 2 paint | Roughly 1.5–2x | Flat, true, professional |
| Re-plaster first, then skim+putty+paint | Full build-up | Whole new budget conversation | Depends entirely on the re-plaster |

Two honest rules: gypsum skim costs more per bag than cement but covers the drama of mixing skill; and labour is usually the deciding line, not material — skimming and sanding are skilled, slow stages. Rather than trusting any fixed price list, size your own rooms and price current materials with the [finishing estimator](/finish-estimator).

## Choosing in Practice — A Decision Path

1. Straightedge the wall. Deviations under 2 mm? → putty + primer + paint.
2. Deviations 2 to 5 mm, sound plaster? → skim + putty + primer + paint.
3. Hollow-sounding patches or cracks wider than hairline? → cut out and re-plaster those areas first, then step 2.
4. Wall damp (polythene test shows condensation)? → stop, find the moisture source, wait. No coating system survives an active damp problem.
5. Exterior or wet-area walls? → cement-based route only, plus waterproofing considerations — gypsum has no place where water is in play.
6. Previously painted wall? → test adhesion with tape before trusting any of the routes above; loose old film over-rides everything else. The [surface-by-surface guide](/learn/choosing-right-finish-different-surfaces) handles that case fully.

## A Worked Comparison — The Same Room, Three Ways

Take a 4.8 × 3.6 m living room, 3 m ceiling, roughly 45 m² of net wall plus 17 m² of ceiling, in three starting conditions:

**Condition A — good machine plaster (1 mm deviations).** Route: prime, two coats. The wall was genuinely ready; total material cost is the base case, and the finish reads professionally. Adding skim here would have spent a full extra stage on nothing.

**Condition B — typical hand plaster (3 mm ripple).** Route: skim, putty, prime, two coats. Materials run to roughly 1.5 to 2 times the base case, plus the labour of the skim and sanding days — the normal, worth-it cost of a flat wall.

**Condition C — rippled plaster plus one hollow patch.** Route: cut back and re-plaster the patch first, then Condition B's full route. The localized repair adds a day and a small materials line, and skipping it would have made the skim a skin over a void — the patch would drum through the paint within a year.

The lesson from running the same room three ways: the differences in cost and outcome are driven almost entirely by the wall's starting condition, and by whether the assessment honestly recorded it. That is why every serious quote starts with a straightedge, not a price list.

## Storage, Shelf Life, and the Quality You Cannot See

These materials fail silently before they ever reach the wall, so buying well matters as much as applying well:

**Cement** loses strength with age and moisture. A bag that has been sitting in a damp shop corner for six months has already lost a real fraction of its binding power. Check the manufacturing date, squeeze the bag — lumps mean it has begun setting — and buy from a shop with fast stock turnover.

**Gypsum skim** is hydroscopic: an opened or badly stored bag absorbs humidity from the air, and the material then sets faster, works rougher, and loses the smooth open time you are paying for. Buy bags with intact liners, store off the floor in dry rooms, and once opened, seal and use within weeks, not months.

**Putty** in tubs separates with age — stir to a uniform cream before use; if it has skinned, lumps, or smells sour, it is past its best. Acrylic putties survive storage better than gypsum-based ones; either way, a tub that has frozen or baked in a vehicle should be inspected, not trusted.

**Paint and primer** should be stirred from the bottom, and any tin with rust on the seam or a gelled layer under the lid is already compromised. The general rule across all four materials: buy from a busy shop, check dates, store dry, and never buy the ".managed" discount bag at the back — the wall will announce its provenance within a season.

## How to Brief Whoever Applies It

The materials come with no opinions — the applicator supplies those, and a wrong briefing produces the classic silent substitutions. Three sentences in your brief prevent most of them:

1. **"Assess first, in writing."** Whoever applies must record deviations and hollows per wall before mixing anything. An applicator who will not straightedge the wall is an applicator planning to guess.
2. **"Two thin passes, feathered."** Say it for skim even if it sounds obvious — single thick passes are the industry's favourite economy, and they are the direct source of map cracks.
3. **"Putty and primer are not optional stages."** The two stages most often "skipped to save you money" are precisely the two whose absence cannot be seen on completion day and cannot be hidden a season later.

Then hold the torch checks yourself between stages. Materials respond to the sequence, and the sequence only exists if someone verifies it.

## How the Layers Fail When Skipped — a Cost View

Each layer skipped has a specific, predictable bill:

| Skipped layer | First symptom | Typical timeline | The eventual bill |
|---|---|---|---|
| Assessment | Wrong system bought entirely | Visible at completion under raking light | Redo the correct system, full cost twice |
| Skim (where needed) | Ripple in evening light | Day one — permanent | The paint cannot be made to hide it; re-skim and repaint |
| Putty | Pinholes framing in sheen | After second coat | Full putty + prime + repaint cycle |
| Primer | Patchy sheen, poor adhesion | Weeks to one season | Strip peeling areas, prime, recoat |
| Correct curing time | Bubbles, blotches, peeling | First humid season | Strip to sound layer and redo |

The pattern across every row: the skipped stage is invisible at handover and expensive at discovery. That asymmetry — free to skip, costly to discover — is why finishing is where project money quietly goes to die, and why the five-line sequence (assess, level, fill, seal, decorate) is worth treating as a contract rather than a suggestion.

## Quick Answers to Counter Questions

**"Can I use putty instead of skim — it is cheaper?"** Only if the wall's deviations are genuinely under about 2 mm. Putty stacked thick to fake a skim cracks and flakes — it is a pore filler, not a leveller. When someone quotes "all-in-one putty finish", ask to see a wall they did that way eighteen months ago.

**"Is gypsum skim the same as POP?"** No — POP (plaster of Paris) is the casting/ceiling product; bagged wall skim is a formulated finishing compound with retarders and fillers that give working time and sandability. Raw POP sets too fast and sands too soft for wall skimming, though the chemistry is related.

**"Do I need putty if I use gypsum skim?"** Usually yes — gypsum skim still leaves pinholes at trowel boundaries. The putty pass is quick and cheap insurance; the paint will report every skipped pinhole in sheen.

**"Can cement-based skim go over gypsum skim or vice versa?"** Do not mix the families in one build-up. Gypsum over a dry cement base is workable in practice; cement over gypsum is a rejection risk, because cement's alkalinity and water attack the gypsum layer beneath. Plan the build-up in one family from the start.

**"Which comes first on bad walls — repairs or skim?"** Repairs, always, and cured repairs at that. Skimming over fresh repair patches in the same day seals their shrinkage in, and the outline of every patch telegraphs through the paint in months.

**"How do I know a quoted 'skim' is really skim?"** Ask two questions: what thickness, and how many passes. A genuine skim is 2 to 5 mm in two thin passes with sanding after; a fake skim is one thick scrape of filler that will map-crack by month two. If the answer is vague, the wall is being textured with whatever is cheapest — put your straightedge and torch checks in writing and watch the answers sharpen.

## Closing

Skim coat, putty, and paint are one system seen from three angles: skim for trueness, putty for pores, paint for appearance — with primer quietly holding all of them to the wall. Buy the layers your wall's condition demands, not the ones the counter suggests. For a room-by-room quantity and cost picture of whichever route you choose, run the [finishing estimator](/finish-estimator); for the full application sequence, see the [complete guide to interior wall finishing](/learn/complete-guide-interior-wall-finishing).
