## Introduction

How do you know a finishing job is actually good — before you pay the final balance? Most clients judge by how a wall looks at noon under one ceiling light. A professional checks it under raking light, across a straight edge, and after the paint has dried.

This guide translates the finishing trade's unwritten quality standards into an inspection list anyone can use: surface flatness tolerances, what counts as acceptable hairline cracking, paint coat counts, edge and corner sharpness, and the tell-tale signs of skipped preparation hidden under a beautiful first impression.

## The Standard — Measurable, Not a Matter of Taste

A finished wall either meets numbers or it does not. The numbers professionals use:

| Check | Instrument | Pass standard |
|---|---|---|
| Flatness | 1.5–2 m straightedge | No gap over ~3 mm anywhere on the wall |
| Surface texture | Bare palm + raking torch | No snags, no grit, no ripple shadows |
| Pinholes | Raking torch at 200 mm | No visible pinholes after final coat |
| Sheen uniformity | Daylight at shallow angle, whole wall | No patchy gloss differences between sections |
| Coating count | Edge sanded through a discreet corner | Full primer + stated topcoats present |
| Edges and corners | Fingertip + eye | Straight, sharp, no paint-on-fittings, no misses |
| Adhesion | Tape test on discreet spot | No film lifts with the tape |

Write the tolerances into the scope before work starts — "no gap over 3 mm under a 2 m straightedge" is a standard; "smooth" is a mood.

## The Raking-Light Inspection — the Professional's Tool

Raking light — a bright torch held nearly parallel to the wall — is the trade's lie detector, because it converts defects into shadows. The inspection takes two minutes per room:

1. **Darken the room** as far as practical.
2. **Sweep the torch flat along each wall** — top to bottom, corner to corner.
3. **Read the shadows:** ripples cast long soft shadows; pinholes are dots of dark; lap marks are glossy bars; patch repairs are clouds; roller debris is small hard shadows.
4. **Do it at the final balance stage**, not at handover-day chit-chat — after the last coat is fully dried, because some defects (patchy sheen) only appear when the film has cured.

Everything the torch finds at payment time was findable with the same torch at skim stage for a tenth of the cost. That asymmetry is why professionals inspect *during*, not only after.

## Flatness, Cracking, and What "Acceptable" Means

**Flatness.** The 3 mm-under-2 m rule is the honest standard for hand-finished interiors; premium machine-finished work targets less. Deviations beyond tolerance cannot be "touched up" — they are geometry and belong to the skim/plaster stage, not the painter's brush.

**Hairline cracking.** Acceptable: scattered, shallow shrinkage micro-cracks that do not follow a line and do not widen seasonally — common at skim boundaries, stable, cosmetic. Not acceptable: cracks that run diagonally from door/window corners (movement signature), cracks that map in grids across whole sections (thick-coat signature), or any crack you can catch a fingernail in. The seasonal test separates them: measure the same crack in harmattan and again at peak rains — a width that changes is a moving crack, and a verdict, not a blemish.

**Sheen.** Uniform within each wall. Different sheens between rooms may be specified; different sheens *within* a wall mean suction was never sealed — primer was skipped or stretched.

## Coat Counts — the Tell-Tale Signs of Skipped Preparation

The most expensive finishing defects are the ones hidden under a beautiful first impression:

- **Patchy sheen** — primer skipped; the wall absorbed binder unevenly.
- **Pinholes framing in the light** — putty pass skipped; the paint is a photocopy of the skim's pores.
- **Ripple in evening light** — the skim stage was skipped where the wall needed it, or applied in one thick pass.
- **Bubbles and blisters within the first season** — coating over damp or under bad drying conditions; the calendar was skipped, not the paint.
- **Peeling at edges and around repairs first** — adhesion failed at the places preparation matters most: spot-priming was skipped.
- **The "one thick coat" tell** — orange-peel texture in the paint film, slow-drying rooms that smell of solvent for days: a thick single coat where two thin coats were specified.

The common thread: **every one of these is invisible at noon under a ceiling light and unmistakable under a torch or with time.** Hence the professional's inspection order — torch, straightedge, tape, palm — none of which involve an opinion.

## Edges, Corners, and Fittings — the 10% That Reveals the 100%

Corners and edges are where craft is unmistakable, because they cannot be rolled — they are cut in by brush and steadied by hand:

- **Internal corners:** clean and straight, no lumps of paint bridging the angle, no misses in the shadow of the line.
- **External corners and arrises:** straight, sharp, uniform colour both sides — rounded corners or burned-through edges mean the corner bead/arris work under the paint was not done or not protected.
- **Around fittings:** switches, sockets, and plates either removed or masked with a clean edge — paint on fittings and "we'll touch that up" borders are craft verdicts, not details.
- **Skirting and ceiling lines:** a straight cut line, no wobble along its length — a wobbling cut line follows a wobbling arm, and wobble is visible from across the room for the life of the finish.

Run a fingertip along the skirting line and look along it from a shallow angle — this ten-percent of the work predicts the rest.

## The Payment-Stage Inspection — a Walk-Through Protocol

At final inspection (after full cure, before final balance), walk each room in this order:

1. **Daylight pass:** sheen uniformity, colour consistency wall-to-wall, obvious misses.
2. **Torch pass:** ripples, pinholes, patch clouds, lap marks — each wall swept.
3. **Straightedge pass:** the tolerance check on the worst-looking walls and behind doors.
4. **Edge pass:** corners, skirting lines, fittings, behind doors and radiators — the places hurried work hides.
5. **Tape and touch:** one discreet tape test, one bare-palm sweep per room.
6. **Snag list in writing:** every finding marked with painter's tape and photographed; the balance follows the list, not the handshake.

The whole protocol is twenty minutes for a flat — and it converts "it looks nice" into "it passes", which is the difference between buying a finish and renting one until the first rainy season.

## What Good Work Looks Like While It Is Happening

Quality is easier to verify during the job than after it. Signs of a professional sequence in progress: straightedges and torches in use between stages (not just at the end); drying time respected between coats (no same-day skim-prime-paint marathons); buckets and trowels cleaned at day's end; dust wiped before priming; sample panels for any texture or sheen work; and a contractor who welcomes the mid-stage inspection instead of discouraging it. The tradespeople who argue against inspection are telling you what the inspection would find.

## Tolerances by Stage — When to Check What

Quality inspection is not one event; each stage has its own acceptance moment, and defects are cheapest at their own stage:

| Stage | Acceptance check | What it prevents |
|---|---|---|
| After preparation | Tap test clean, repairs cured, wall dust-free, polythene test passed | Coating over hollows and damp — the fatal errors |
| After skim | Straightedge tolerance met; torch quiet on ridges | Sanding-stage discovery, double handling |
| After sanding/putty | Palm-clean, pinholes filled, dust removed | Pinhole photocopying through every later coat |
| After primer | Uniform flat film, no suction patchiness | Sheen defects locked in under topcoats |
| After first topcoat | Torch + edge pass | Final-coat disguise of first-coat defects |
| Final (cured) | The full walk-through protocol | Paying for work that fails within the season |

The professional's habit is refusing to let a stage proceed until the previous stage's check passes — because in this trade, a defect passed forward does not stay hidden; it matures. Every "we'll fix it at the end" becomes either invisible-forever or visible-forever, and nobody can say which until the torch decides.


**A note on "sight tests" versus standards:** the handover-day walk-through with the client is not the inspection — it is the *presentation* of an inspection that already happened. A contractor who passes the torch, straightedge, and tape checks in front of you, room by room, is showing you the same protocol they ran when nobody was watching. That transparency is itself a quality standard: the trade's best signal is not the perfect wall, it is the contractor who checks walls the same way whether or not the client is there.
## After Handover — the Defect Window and the Warranty Conversation

Finishing defects are *timed*: adhesion and moisture failures surface in the first rainy season, sheen and pinhole defects appear under the first evening bulbs, and movement cracks declare themselves across one thermal year. A sensible retention — a small share of the payment held for four to eight weeks after handover — lets that window speak before the money has fully moved.

When a defect appears in the window, diagnose before blaming: the tape test separates adhesion failure from film damage; the torch separates coating defects from geometry; the seasonal measurement separates movement from shrinkage (see the [defects guide](/learn/common-finishing-defects-and-how-to-fix) for the full diagnostic table). A contractor worth retaining responds to a defect map; a contractor worth replacing responds to the invoice only.

## Closing

A good finishing job is measurable: flat within tolerance, silent under raking light, uniform in sheen, full in coat count, sharp at every edge — inspected with tools, not compliments. Write the standards into the scope, inspect during the stages, and pay against the snag list. For the sequence that produces walls meeting these standards, see the [complete guide to interior wall finishing](/learn/complete-guide-interior-wall-finishing); for the defects that betray skipped stages, see [common finishing defects and how to fix](/learn/common-finishing-defects-and-how-to-fix).
