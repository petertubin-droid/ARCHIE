  USING (true);

-- Imports: admin-only (internal operational detail).
DROP POLICY IF EXISTS "admins manage lexicon imports" ON public.lexicon_imports;
CREATE POLICY "admins manage lexicon imports"
  ON public.lexicon_imports FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());
