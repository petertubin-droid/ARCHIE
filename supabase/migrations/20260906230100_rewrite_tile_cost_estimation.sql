## Introduction

Tiling quotes hide their differences in the details: which grout, whose adhesive, what happens to broken tiles, and whether "per square metre" includes the skirting and the cutting waste most rooms demand. Two quotes at the same rate can differ by forty percent in what they actually deliver.

This guide builds a complete tiling budget from the ground up: area measurement done correctly, tile quantity with realistic waste factors, adhesive and grout consumption, labour rates by engagement model across Nigerian cities, and the finishing items — skirting, trims, sealants — that always seem to appear after the quote is accepted. You will finish with a working estimate template of your own.

## The Four Cost Blocks of Any Tiling Job

Every tiling budget, whatever the room, is the sum of four blocks — and most disputes trace to a quote that quietly moved money between them:

1. **Preparation** — old floor removal, screeding or levelling, waterproofing in wet areas, door cutting if the new floor rises above the old clearance
2. **Materials** — tiles, adhesive, grout, spacers, trims, sealant, membrane
3. **Labour** — fixing, cutting, grouting, and often material haulage to upper floors
4. **Finishing** — skirting, edge trims, silicone at junctions, and the final clean

The professional habit is to price each block separately and make the tiler confirm which blocks their quote contains. "₦X per square metre" is meaningless until you know whether it is labour only, labour plus adhesive, or all four blocks.

## Measure First: The Area Every Cost Hangs On

Cost per square metre is only useful if the square metres are correct. Measure each room internally at floor level, wall to finished wall, at two points per wall and record the larger figure. Split irregular rooms into rectangles, sketch each one, and total the areas.

The full measurement and waste-factor method is in [our tile quantity calculation guide](/learn/how-to-calculate-tile-quantities-any-room) — the short version: room area, plus the pattern's waste allowance (10% for straight lay, 15% for diagonal, up to 20% for herringbone), rounded up to whole cartons. Wall tiles in wet areas are measured as height runs per wall, minus doors and windows, at 15% waste.

For the rest of this guide we will use one running example — a 3.6 × 3.3 m bedroom, 11.88 m² of floor, straight-lay 400 × 400 tiles at 10% waste, so **13.07 m² of tile** (11 cartons). Keeping one example through all four blocks is exactly how you should build your own sheet: one column of measurements, four blocks of costs beneath it.

## Materials: Pricing the Room, Not the Sticker

The market prices tiles per carton, but budgets think in naira per square metre. Convert at the shelf: price per carton ÷ coverage per carton. A carton of 400 × 400 covering 1.28 m² at ₦8,000 is ₦6,250/m² — instantly comparable with any other tile regardless of carton size. Never compare tiles by carton price alone; cartons vary in coverage.

**The consumption items scale from your area figures:**

| Material | Planning consumption | Our bedroom example |
|---|---|---|
| Tile adhesive (20 kg bags) | ~4–5 m² per bag for 400 × 400, 10 mm notch | 3 bags |
| Grout (5 kg bags) | ~40 m² at narrow joints — more for wide joints | 1 bag |
| Spacers | 1 bag per room per format | 1 bag |
| Silicone sealant | 1 tube per wet room or per 15 m of junction | 1 tube if en-suite |

Trims and skirting are priced by the linear metre — measure perimeter for skirting, and count exposed edges for trims.

Add the batch-matching rule into the budget consciously: tiles for the whole job, including one spare carton, should be bought in one purchase so shade and calibre codes match. The money you "save" by buying in two batches can be spent twice over finding a discontinued shade two months later.

**Preparation materials are materials too.** If the job needs a levelling compound or a waterproofing membrane, they belong in the materials block with their own quantities — a wet-room membrane kit covers roughly 8–12 m² per kit for two coats, so our example bedroom-turned-bathroom would need two kits.

## Labour: Three Engagement Models and What Each Really Costs

In the Nigerian market, tilers price three ways, and the model changes what your supervision duties are:

**Per square metre** is the cleanest for straight comparative quotes. The rate covers fixing and grouting; confirm explicitly whether adhesive and grout are included or billed as "materials supplied by client". Cheapest headline rate is often labour-only — which hands you the material logistics, and the material risk of buying wrong.

**Daily wage** suits small or complicated jobs — a bathroom with many cuts, a single room, repair work. You pay the day rate times the realistic duration, and you supply or approve materials. The risk is duration drift: agree upfront what "done" means, including grouting and joint cleaning.

**Fixed price** hands the whole scope to the tiler for one number. It is the most comfortable and the most expensive — you are paying for the tiler to carry the risk. A fixed price is only as good as its written scope: which blocks of the four it contains, and what triggers a variation.

Whichever model you choose, get the exclusions in writing: haulage up a flight of stairs, removal of old tiles, skirting, and silicone are the four items most often discovered as extras.

## Preparation: The Block Quotes Love to Forget

Preparation is where two identical-sounding quotes legitimately differ by thousands of naira. Price these as their own lines, even if the answer is "none needed":

- **Old tile removal** — priced per m², and it damages the screed below, so budget screed repair after removal
- **Screeding or levelling** — a new screed to create falls in bathrooms, or self-levelling compound for large-format tiles that telegraph every undulation
- **Waterproofing** — the membrane, the tape, and the labour to apply it properly in any wet area; not optional, and detailed in [our bathroom waterproofing guide](/learn/how-to-tile-bathroom-waterproofing-best-practices)
- **Door adjustment** — a new tiled floor is 15–25 mm higher than the old one; somebody is cutting doors

The check worth doing before accepting any quote: ask the tiler what they found when they looked at the floor, and what preparation they have assumed. A tiler who quotes without asking about the existing floor has already told you what their quote is worth.

## The Worked Budget: One Bedroom, Four Blocks

With method established, here is the complete shape of a real budget for our example bedroom — substitute your own measured figures and local prices and the template is yours:

| Block | Line | Quantity | Basis |
|---|---|---|---|
| Preparation | Self-levelling compound | 2 bags | poor existing screed |
| Materials | 400 × 400 tiles | 11 cartons | 13.07 m² incl. waste + spare |
| Materials | Flexible adhesive | 3 bags | 4.5 m²/bag |
| Materials | Grout, spacers, silicone | 1 each | room-size quantities |
| Labour | Fixing + grouting, per m² | 11.88 m² | rate includes cutting |
| Finishing | Skirting | 13.8 linear m | perimeter minus door |

Two structural notes on using the table. First, the spare carton sits in the materials block on purpose — it is a cost of the job, not a contingency, because batch matching makes it the only way to guarantee the floor matches itself in year three. Second, notice what is not there: no "miscellaneous" line. Every naira in a professional estimate belongs to a named line; the misc line is where budgets go to hide their errors.

## Comparing Quotes Line by Line

When the quotes arrive, lay them side by side and check each one against your own four-block estimate — not against each other. For each quote, find out:

- Which of the four blocks does it include? (Ask directly; do not assume.)
- What adhesive and grout grade does it price — and does the grade match the tiles you chose?
- What waste factor is built into the tile quantity?
- Who carries breakage risk: tiles broken in cutting — the most contested naira in tiling?
- What is the exclusions list, and does it match the four common ones (haulage, removal, skirting, silicone)?
- What triggers a variation, and what does a variation cost?

A quote that survives all six questions at a slightly higher price is cheaper than a quote that fails two of them at any price.

## Contingency and Cash Flow

Budget 10% contingency on the whole job — real jobs discover real surprises under old floors. Hold it separately and release it only for named discoveries, not for scope drift.

On cash flow, the standard rhythm protects both sides: materials deposit, then staged payments tied to finished stages (not calendar dates) — fixing complete, then grouting complete, with a retention held until the final clean and joint inspection. A tiler who resists stage-based payment is telling you something; so is a client who resists a retention.

## Conclusion

A tiling budget you can trust is four honest blocks — preparation, materials, labour, finishing — each with quantities from real measurements and rates you have verified against your own area figures. Build it once with this guide's template and any quote in your hand becomes readable: you will see what it includes, what it omits, and what it is really worth.

Run your measured areas through the [tile calculator](/tile-calculator) for quantities, then price the four blocks against your local market — and when a quote arrives, compare it to your estimate, not to another quote.
